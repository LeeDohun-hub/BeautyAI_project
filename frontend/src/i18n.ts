export interface AppLangValue {
  lang: AppLang;
  setLang: (lang: AppLang) => void;
}

export const AppLangContext = createContext<AppLangValue>({ lang: 'ko', setLang: () => undefined });

/** 화면 문자열 번역기. `t('한국어 원문')` — 사전에 없으면 원문을 그대로 반환한다. */
export function useT(): (ko: string) => string {
  const { lang } = useContext(AppLangContext);
  return (ko: string) => (lang === 'ja' ? JA[ko] ?? ko : ko);
}

export function useAppLang(): AppLangValue {
  return useContext(AppLangContext);
}

/** 사전 적용률(디버그/진행도 확인용). */
export function jaCoverage(): number {
  return Object.keys(JA).length;
}
